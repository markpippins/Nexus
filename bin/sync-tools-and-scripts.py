#!/usr/bin/env python3
"""
bin/sync-tools-and-scripts.py — keep the nebula "Tools & Scripts" catalog in sync with nexus/bin/, nexus/tools/, nexus/go/, and nexus/rust/.

Every script in nexus/bin/ (Bash + Python subsystems), every tool in
nexus/tools/ (Tools subsystem), every package in nexus/go/wrp/ccnf-ref
(Go subsystem), and every module in nexus/rust/wrp/ccnf-verifier/src
(Rust subsystem) is expected to appear as a feature in the "Tools &
Scripts" system with context documentation. This tool makes that true:

  * Scans bin/, tools/, go/, and rust/.
  * Registers anything missing as a feature (idempotent — safe to re-run;
    existing features are left untouched).
  * Auto-generates the context documentation (readme) from the script's own
    --help output, or failing that from its header comments / module
    docstring. For Go/Rust packages the readme comes from `go doc` /
    module doc comments. Auto-generated readmes carry a footer marker so
    they can be refreshed later.

Granularity:
  * File entries (bin/, tools/): one feature per script/tool file.
  * Package entries (go/, rust/): one feature per Go package dir or Rust
    module (src/* dir or src/*.rs file), keyed by the feature's `path`
    field (e.g. go/wrp/ccnf-ref/ccnf).

Modes:
  (default)      Register any unregistered scripts/tools.
  --check        Report-only: exit 1 if anything on disk is unregistered
                 (or any registered feature's file is gone). For CI / pre-push.
  --refresh      Regenerate readmes for auto-generated features (footer marker
                 present) whose file has changed since the readme was written.
                 Hand-authored readmes are NEVER touched.
  --force        With --refresh: regenerate even when the file is unchanged.

Run with: python3 bin/sync-tools-and-scripts.py [--check|--refresh] [--force]
"""
import argparse
import json
import os
import re
import subprocess
import sys
import urllib.request

API = "http://localhost:3101"
TOOLS_SYSTEM = "Tools & Scripts"
FOOTER = (
    "\n\n---\n*Auto-generated by bin/sync-tools-and-scripts.py. "
    "Regenerate with `python3 bin/sync-tools-and-scripts.py --refresh`. "
    "Edit the script's --help text or header comments instead of this text.*"
)
# Distinctive marker used to detect auto-generated readmes. The first
# splitlines() element of FOOTER is empty (leading \n\n), so test for the
# actual marker text instead — otherwise the guard never fires and
# hand-authored readmes get recomposed.
AUTO_MARKER = "Auto-generated by bin/sync-tools-and-scripts.py"

# Catalog entries: which dir maps to which subsystem.
#   dir        — scan target (relative to repo root)
#   sub        — subsystem name under "Tools & Scripts"
#   path       — path value stored on the feature (prefix for file entries,
#                exact package path for package entries)
#   exts       — file extensions to include
#   recursive  — scan subdirectories
#   granularity— "file" (one feature per file) or "package" (one feature per
#                Go package dir / Rust module)
#   lang       — for package entries: "go" | "rust" (readme composition)
#   label      — description suffix
CATALOG = [
    {"dir": "bin",   "sub": "Bash",   "path": "scripts/bash", "exts": (".sh",),        "recursive": False, "granularity": "file",    "label": "Shell script in nexus/bin/"},
    {"dir": "bin",   "sub": "Python", "path": "scripts/",     "exts": (".py",),        "recursive": False, "granularity": "file",    "label": "Python script in nexus/bin/"},
    {"dir": "tools", "sub": "Tools",  "path": "tools/",       "exts": (".py", ".sql"), "recursive": True,  "granularity": "file",    "label": "Tool in nexus/tools/"},
    {"dir": "go/wrp/ccnf-ref",  "sub": "Go",   "path": "go/wrp/ccnf-ref",          "exts": (".go",), "recursive": True, "granularity": "package", "lang": "go",   "label": "Go package in nexus/go/wrp/ccnf-ref/"},
    {"dir": "rust/wrp/ccnf-verifier/src", "sub": "Rust", "path": "rust/wrp/ccnf-verifier/src", "exts": (".rs",), "recursive": False, "granularity": "package", "lang": "rust", "label": "Rust module in nexus/rust/wrp/ccnf-verifier/src/"},
]
SKIP_PARTS = {"__pycache__", "__init__", "target", "vendor"}


def api(method, path, payload=None):
    body = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(
        f"{API}{path}", data=body,
        headers={"Content-Type": "application/json"}, method=method,
    )
    with urllib.request.urlopen(req, timeout=10) as r:
        return json.load(r)


def load_catalog():
    """Return (subsystems_by_name, features_by_filekey, features_by_pkgpath)."""
    systems = api("GET", "/api/systems")["items"]
    tools = next((s for s in systems if s["name"] == TOOLS_SYSTEM), None)
    if tools is None:
        sys.exit(f"ERROR: system '{TOOLS_SYSTEM}' not found in nebula")
    subs = {sub["name"]: sub for sub in tools["subsystems"]}
    feats = [f for sub in subs.values() for f in sub["features"]]
    by_file = {}
    by_pkg = {}
    for f in feats:
        desc = f.get("description") or ""
        m = re.match(r"^([\w\-. /]+\.(?:sh|py|sql|go|rs))\s*—", desc)
        if m:
            by_file[m.group(1)] = f
        if f.get("path"):
            by_pkg[f["path"]] = f
    return subs, by_file, by_pkg


def scan_files(entry, repo_root):
    """Return sorted relpaths (os-relative to the entry dir) for file entries."""
    root = os.path.join(repo_root, entry["dir"])
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
        for fn in sorted(filenames):
            stem = fn.rsplit(".", 1)[0]
            if (stem in SKIP_PARTS or fn.startswith("__") or fn.startswith("test_")
                    or fn.endswith((".pyc", ".pyo"))):
                continue
            if fn.endswith(entry["exts"]):
                rel = os.path.relpath(os.path.join(dirpath, fn), root)
                if entry["recursive"] or os.sep not in rel:
                    out.append(rel)
    return out


def scan_packages(entry, repo_root):
    """Return sorted package relpaths (os-relative to the entry dir).

    Go: every dir under the root containing >=1 non-test .go file.
    Rust: every src/* dir containing .rs files, plus src/*.rs files.
    """
    root = os.path.join(repo_root, entry["dir"])
    if entry.get("lang") == "go":
        out = []
        for dirpath, dirnames, filenames in os.walk(root):
            dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
            has_src = any(fn.endswith(".go") and not fn.endswith("_test.go")
                          for fn in filenames)
            if has_src:
                rel = os.path.relpath(dirpath, root)
                if rel != ".":
                    out.append(rel.replace(os.sep, "/"))
        return sorted(out)
    # Rust: top-level dirs + top-level .rs files under src/
    out = []
    for name in sorted(os.listdir(root)):
        full = os.path.join(root, name)
        if os.path.isdir(full) and name not in SKIP_PARTS:
            if any(fn.endswith(".rs") for fn in os.listdir(full)):
                out.append(name)
        elif os.path.isfile(full) and name.endswith(".rs"):
            out.append(name)
    return out


def humanize(relpath):
    """api-docs/check_drift.py -> Api Docs Check Drift; batch_harvest_to_db.py -> Batch Harvest To Db."""
    parts = relpath.rsplit(".", 1)[0].split(os.sep)
    words = []
    for part in parts:
        words.extend(re.split(r"[_\-]+", part))
    out = []
    for w in words:
        if not w:
            continue
        # Preserve internal camelCase (e.g. InProgress); otherwise capitalize.
        if any(c.isupper() for c in w[1:]):
            out.append(w)
        else:
            out.append(w.capitalize())
    return " ".join(out)


def run_help(path, cwd):
    """Try `python3 <file> --help`; return (ok, text)."""
    for flag in ("--help", "-h"):
        try:
            r = subprocess.run(
                ["python3", os.path.abspath(path)], capture_output=True, text=True,
                timeout=12, cwd=cwd,
            )
            text = r.stdout + r.stderr
            if r.returncode == 0 and "usage:" in text and "Traceback" not in text:
                return True, text
        except (subprocess.TimeoutExpired, FileNotFoundError):
            pass
    return False, ""


def header_docs(path):
    """Extract the leading comment block / module docstring as documentation."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return ""
    doc, in_docstring = [], False
    for ln in lines[:60]:
        s = ln.strip()
        if s.startswith(("#!", "set ")):
            continue
        if s.startswith(('"""', "'''")) or s in ('"""', "'''"):
            in_docstring = True
            doc.append(s.strip('"\''))
            continue
        if in_docstring:
            if s in ('"""', "'''") or s.endswith(('"""', "'''")):
                doc.append(s.strip('"\''))
                break
            doc.append(s)
            continue
        if s.startswith(("#", "--")):
            doc.append(s.lstrip("#- "))
            continue
        if s == "":
            if doc:
                break
            continue
        break
    return "\n".join(x for x in doc if x).strip()


def compose_readme(path, cwd):
    """Return (readme, auto_generated) for a script/tool file."""
    ok, text = run_help(path, cwd)
    if ok:
        usage = next((l for l in text.splitlines() if l.strip().startswith("usage:")), "")
        desc_lines, options = [], []
        in_opts = False
        for l in text.splitlines():
            s = l.strip()
            if s == "options:" or s.startswith("options:"):
                in_opts = True
                continue
            if in_opts:
                if s:
                    options.append(s)
                continue
            if (s and not s.startswith("usage:") and not s.startswith("positional arguments:")
                    and not s.startswith("[")):
                desc_lines.append(s)
        parts = []
        if desc_lines:
            parts.append("\n".join(desc_lines))
        if usage:
            parts.append(f"Usage: `{usage[6:].strip()}`")
        if options:
            parts.append("Options:\n" + "\n".join(f"- {o}" for o in options))
        return ("\n\n".join(parts) + FOOTER), True
    docs = header_docs(path)
    if docs:
        return docs + FOOTER, True
    return (
        f"Runs `{os.path.basename(path)}` from `nexus/{os.path.relpath(os.path.dirname(path), cwd)}/`. "
        f"See the source for usage details." + FOOTER,
        True,
    )


def rust_doc_lines(path):
    """Extract leading `//!` / `///` doc comments from a Rust file."""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
    except OSError:
        return ""
    out = []
    for ln in lines[:60]:
        s = ln.strip()
        if s.startswith("//!"):
            out.append(s.lstrip("//!").strip())
        elif s.startswith("///"):
            out.append(s.lstrip("///").strip())
        elif s.startswith("/*!"):
            out.append(s.lstrip("/*!").strip())
            continue
        elif s == "":
            if out:
                break
            continue
        elif s.startswith(("use ", "pub ", "fn ", "mod ", "struct ", "enum ", "type ", "const ", "impl ")):
            break
        else:
            if out:
                break
    return "\n".join(x for x in out if x).strip()


def package_mtime(entry, abs_target, pkg_rel):
    """Most recent mtime across the package's source files."""
    if os.path.isfile(abs_target):
        return os.path.getmtime(abs_target)
    newest = 0.0
    for dirpath, dirnames, filenames in os.walk(abs_target):
        dirnames[:] = [d for d in dirnames if d not in SKIP_PARTS]
        for fn in filenames:
            if fn.endswith(entry["exts"]):
                newest = max(newest, os.path.getmtime(os.path.join(dirpath, fn)))
    return newest


def package_file_inventory(entry, pkg_rel):
    """List the source files that make up a Go package / Rust module."""
    root = os.path.join(entry["dir"], pkg_rel)
    if os.path.isfile(root):
        return [os.path.basename(root)]
    try:
        names = sorted(os.listdir(root))
    except OSError:
        return []
    if entry.get("lang") == "go":
        return [n for n in names if n.endswith(".go") and not n.endswith("_test.go")]
    return [n for n in names if n.endswith(".rs")]


def compose_package_readme(entry, pkg_rel, repo_root):
    """Return (readme, auto_generated) for a Go/Rust package feature."""
    abs_target = os.path.join(repo_root, entry["dir"], pkg_rel)
    base = os.path.join(repo_root, entry["dir"])
    parts = []
    if entry.get("lang") == "go":
        try:
            r = subprocess.run(
                ["go", "doc", "./" + pkg_rel], capture_output=True, text=True,
                timeout=20, cwd=base,
            )
            if r.returncode == 0 and r.stdout.strip():
                parts.append(r.stdout.strip())
        except (subprocess.TimeoutExpired, FileNotFoundError):
            pass
        if not parts:
            docs = header_docs(os.path.join(abs_target, os.path.basename(pkg_rel) + ".go")) \
                if os.path.isdir(abs_target) else ""
            if docs:
                parts.append(docs)
        test_hint = f"Run with: `go test ./{pkg_rel}/...` (from go/wrp/ccnf-ref)"
    else:
        mod_file = os.path.join(abs_target, "mod.rs") if os.path.isdir(abs_target) else abs_target
        docs = rust_doc_lines(mod_file) if os.path.isfile(mod_file) else ""
        if docs:
            parts.append(docs)
        test_hint = "Run with: `cargo test` (from rust/wrp/ccnf-verifier)"
    files = package_file_inventory(entry, pkg_rel)
    if files:
        parts.append("Files: " + ", ".join(files))
    parts.append(test_hint)
    return ("\n\n".join(parts) + FOOTER), True


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    ap.add_argument("--check", action="store_true", help="report-only; exit 1 on drift")
    ap.add_argument("--refresh", action="store_true", help="regenerate auto-generated readmes")
    ap.add_argument("--force", action="store_true", help="with --refresh, ignore change detection")
    args = ap.parse_args()

    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    subs, by_file, by_pkg = load_catalog()

    # --- scan all catalog dirs, build relpath -> (entry, abs path) ----------
    on_disk = {}          # file relpath -> entry
    on_disk_pkgs = {}     # package path (repo-relative) -> entry
    for entry in CATALOG:
        if entry["granularity"] == "package":
            for rel in scan_packages(entry, repo_root):
                on_disk_pkgs[f"{entry['dir']}/{rel}"] = entry
        else:
            for rel in scan_files(entry, repo_root):
                on_disk[rel] = entry

    # --- drift report -------------------------------------------------------
    unregistered = []
    for rel, entry in on_disk.items():
        if rel not in by_file:
            unregistered.append((entry["sub"], rel))
    unregistered_pkgs = []
    for pkg, entry in on_disk_pkgs.items():
        if pkg not in by_pkg:
            unregistered_pkgs.append((entry["sub"], pkg))

    stale = []
    for rel, feat in by_file.items():
        if rel in on_disk:
            continue
        alt = None
        if feat.get("path") == "legacy/python":
            alt = os.path.join(os.path.dirname(repo_root), "legacy", "python", rel)
        if alt is None or not os.path.isfile(alt):
            stale.append((feat["name"], rel))
    stale_pkgs = []
    for pkg, feat in by_pkg.items():
        if pkg in on_disk_pkgs:
            continue
        # package features whose path is a prefix (scripts/, tools/, bin) are
        # file-granularity; only flag repo-relative package paths
        if pkg.startswith(("go/", "rust/")):
            stale_pkgs.append((feat["name"], pkg))

    if args.check:
        drift = bool(unregistered or stale or unregistered_pkgs or stale_pkgs)
        for sub, rel in sorted(unregistered):
            print(f"UNREGISTERED [{sub}]: {rel}")
        for sub, pkg in sorted(unregistered_pkgs):
            print(f"UNREGISTERED [{sub}] (package): {pkg}")
        for name, rel in stale:
            print(f"STALE: feature '{name}' -> {rel} not on disk")
        for name, pkg in stale_pkgs:
            print(f"STALE: feature '{name}' -> {pkg} not on disk")
        if drift:
            print("\nRun: python3 bin/sync-tools-and-scripts.py  (registers missing scripts/tools)")
            return 1
        print(f"OK: {len(on_disk)} scripts/tools + {len(on_disk_pkgs)} packages registered, catalog in sync")
        return 0

    # --- register missing ---------------------------------------------------
    created = 0
    for sub, rel in sorted(unregistered):
        entry = on_disk[rel]
        abs_path = os.path.join(repo_root, entry["dir"], rel)
        readme, _ = compose_readme(abs_path, repo_root)
        payload = {
            "subsystemId": subs[entry["sub"]]["id"],
            "name": humanize(rel),
            "description": f"{rel} — {entry['label']}",
            "readme": readme,
            "path": entry["path"],
        }
        api("POST", "/api/features", payload)
        created += 1
        print(f"REGISTERED [{sub}]: {rel} -> feature '{humanize(rel)}'")
    for sub, pkg in sorted(unregistered_pkgs):
        entry = on_disk_pkgs[pkg]
        readme, _ = compose_package_readme(entry, pkg[len(entry["dir"]) + 1:], repo_root)
        payload = {
            "subsystemId": subs[entry["sub"]]["id"],
            "name": humanize(pkg[len(entry["dir"]) + 1:]),
            "description": f"{pkg} — {entry['label']}",
            "readme": readme,
            "path": pkg,
        }
        api("POST", "/api/features", payload)
        created += 1
        print(f"REGISTERED [{sub}] (package): {pkg} -> feature '{humanize(pkg[len(entry['dir']) + 1:])}'")
    for name, rel in stale:
        print(f"NOTE: feature '{name}' references {rel} which is not on disk")
    for name, pkg in stale_pkgs:
        print(f"NOTE: feature '{name}' references {pkg} which is not on disk")

    # --- refresh auto-generated readmes -------------------------------------
    if args.refresh:
        all_feats = {f["id"]: f for f in by_file.values()}
        all_feats.update({f["id"]: f for f in by_pkg.values()})
        refreshed = 0
        for feat in all_feats.values():
            readme = feat.get("readme") or ""
            if AUTO_MARKER not in readme:
                continue  # hand-authored — never touch
            pkg = feat.get("path") or ""
            if pkg in on_disk_pkgs:
                entry = on_disk_pkgs[pkg]
                rel = pkg[len(entry["dir"]) + 1:]
                if not args.force:
                    abs_pkg = os.path.join(repo_root, entry["dir"], rel)
                    mtime = package_mtime(entry, abs_pkg, rel)
                    updated = feat.get("updatedAt") or feat.get("createdAt") or 0
                    if isinstance(updated, (int, float)) and updated / 1000.0 > mtime:
                        print(f"UNCHANGED: {pkg}")
                        continue  # readme newer than package
                new_readme, _ = compose_package_readme(entry, rel, repo_root)
            else:
                # file-granularity: find by description key
                desc = feat.get("description") or ""
                m = re.match(r"^([\w\-. /]+\.(?:sh|py|sql|go|rs))\s*—", desc)
                if not m or m.group(1) not in on_disk:
                    continue
                rel = m.group(1)
                entry = on_disk[rel]
                abs_path = os.path.join(repo_root, entry["dir"], rel)
                if not args.force:
                    mtime = os.path.getmtime(abs_path)
                    updated = feat.get("updatedAt") or feat.get("createdAt") or 0
                    if isinstance(updated, (int, float)) and updated / 1000.0 > mtime:
                        continue  # readme newer than file
                new_readme, _ = compose_readme(abs_path, repo_root)
            if new_readme != readme:
                api("PATCH", f"/api/features/{feat['id']}", {"readme": new_readme})
                refreshed += 1
                print(f"REFRESHED: {pkg or rel}")
            else:
                print(f"UNCHANGED: {pkg or rel}")

    print(f"\nDone. {created} registered, {len(on_disk)} scripts/tools + "
          f"{len(on_disk_pkgs)} packages on disk, "
          f"{len(by_file) + len(by_pkg) + created - len(stale) - len(stale_pkgs)} features in catalog.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
